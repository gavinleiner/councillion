import {writeFile} from 'node:fs/promises';
import {randomBytes,createHash} from 'node:crypto';
import {MIXED_PACKS} from '../data.js';
import {QUESTION_QUALITY_BUILD} from '../question-quality.js';
import {sampleQuestionPool} from '../question-sample-selection.js';

const supplied=process.argv.find(a=>a.startsWith('--seed='))?.slice(7);
if(!supplied&&!process.argv.includes('--new'))throw Error('Use --seed=VALUE to reproduce a draw, or --new to create one deliberately.');
const categories=MIXED_PACKS.map(p=>({id:p.id,prompt:p.prompt,family:p.family,group:p.group,answerCount:p.answerCount,scope:p.scope??''}));
const manifest={build:createHash('sha256').update(QUESTION_QUALITY_BUILD+JSON.stringify(categories)).digest('hex').slice(0,16),count:categories.length,categories};
await writeFile(new URL('../ordinary-question-pool.json',import.meta.url),JSON.stringify(manifest,null,2)+'\n');
await writeFile(new URL('../ordinary-question-list.csv',import.meta.url),'id,subject,question,canonical_answers\n'+categories.map(p=>[p.id,p.family,p.prompt,p.answerCount].map(v=>'\"'+String(v).replaceAll('\"','\"\"')+'\"').join(',')).join('\n')+'\n');
const sample=sampleQuestionPool(manifest.categories,{seed:supplied??randomBytes(12).toString('hex'),build:manifest.build});
const base=new URL('../',import.meta.url);
await writeFile(new URL('question-sample.js',base),'// Frozen random draw from the published pool. Generated by scripts/build-question-sample.mjs.\nexport const QUESTION_SAMPLE='+JSON.stringify(sample,null,2)+';\n');
await writeFile(new URL('question-sample-100.json',base),JSON.stringify(sample,null,2)+'\n');
console.log(JSON.stringify({seed:sample.seed,questions:sample.questions.length,families:sample.families,formats:sample.formats},null,2));
